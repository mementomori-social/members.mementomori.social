<h3>1. Name and domicile of the association</h3>
<p>The name of the association is Mementomori ry and its domicile is Jyväskylä.</p>

<h3>2. Purpose and nature of activities</h3>
<p>
	The purpose of the association is to promote open, European, decentralised and digitally sovereign
	social media, as well as open and ethical online communication. The purpose of the association is
	not to generate profit or other financial gain for those involved in it, and its activities are
	not directed at a limited group of people only. Use of the servers maintained by the association
	is open and free of charge and does not require membership.
</p>
<p>To fulfil its purpose, the association:</p>
<ul>
	<li>may organise courses, training and teaching events and other similar activities</li>
	<li>may organise competitions, exhibitions, excursions, camps and other events</li>
	<li>may maintain the association's electronic communication channels</li>
	<li>may publish the association's bulletins and other communications in various channels</li>
	<li>advises and guides its members</li>
	<li>takes part in public discussion on matters related to the field</li>
	<li>may gather and share information and carry out research</li>
	<li>
		brings members together for shared activities and maintains contacts with other associations in
		the field
	</li>
	<li>may organise trips related to the association's purpose for its members</li>
	<li>may acquire the materials and equipment needed for the association's use</li>
	<li>seeks to arrange premises for its use that the association's members may use</li>
	<li>may make proposals and initiatives to increase opportunities for the hobby</li>
	<li>
		may make proposals, initiatives and reports, and give statements to other organisations and
		authorities
	</li>
	<li>promotes the visibility and ethics of open source and decentralised media</li>
	<li>
		maintains and develops community servers and electronic communication channels that are open and
		free of charge to the public as part of the fediverse (for example the services
		mementomori.social and chat.mementomori.social)
	</li>
</ul>
<p>To support its activities, the association may, having obtained any necessary permit:</p>
<ul>
	<li>organise fundraising campaigns and lotteries</li>
	<li>accept grants, donations and bequests</li>
	<li>sell advertising space</li>
	<li>enter into sponsorship agreements</li>
</ul>

<h3>3. Members</h3>
<p>
	A person who accepts the purpose of the association may be approved as a full member of the
	association. A private person or a legal entity that wishes to support the purpose and activities
	of the association may be approved as a supporting member. Full members and supporting members are
	approved by the board of the association upon application. A person who has substantially promoted
	and supported the activities of the association may, on the proposal of the board, be invited at a
	meeting of the association to become an honorary chairperson or an honorary member.
</p>

<h3>4. Joining fee and membership fee</h3>
<p>
	The annual general meeting decides on the amount of the joining fee and the annual membership fee
	charged from full members and supporting members, separately for each group of members. The
	honorary chairperson and honorary members do not pay membership fees.
</p>

<h3>5. Board</h3>
<p>
	The affairs of the association are managed by the board, which consists of a chairperson and 2-4
	other full members elected at the annual general meeting. The term of the board runs between
	electing meetings.
</p>
<p>
	The board elects a vice chairperson from among its members and appoints, from among its members or
	outside them, a secretary, a treasurer and any other officers needed. The board convenes at the
	invitation of the chairperson or, if the chairperson is prevented, of the vice chairperson, when
	they see reason to do so or when at least half of the board members so demand. The board has a
	quorum when at least half of its members, including the chairperson or the vice chairperson, are
	present. Votes are decided by an absolute majority. In the event of a tie, the chairperson's vote
	decides; in elections, however, the tie is decided by lot.
</p>

<h3>6. Signing for the association</h3>
<p>
	The name of the association is signed by the chairperson of the board alone, or by the vice
	chairperson, the secretary, the treasurer or a person authorised by the board, two together.
</p>

<h3>7. Financial year</h3>
<p>The financial year of the association is the calendar year.</p>

<h3>8. Meetings of the association</h3>
<p>
	A meeting of the association may also be attended by post or by means of a telecommunications
	connection or another technical aid during the meeting or before it, if the board or the meeting
	of the association so decides. The meeting of the association approves the voting and election
	rules.
</p>
<p>
	The annual general meeting of the association is held yearly on a date determined by the board
	between January and May.
</p>
<p>
	At meetings of the association, every full member, the honorary chairperson and every honorary
	member has one vote. A supporting member has the right to be present and to speak at the meeting.
</p>
<p>
	Unless otherwise provided in these rules, the decision of a meeting of the association is the
	opinion supported by more than half of the votes cast. In the event of a tie, the vote of the
	chairperson of the meeting decides; in elections, however, the tie is decided by lot.
</p>

<h3>9. Convening meetings of the association</h3>
<p>
	The board must convene the meetings of the association at least 14 days before the meeting. The
	notice of the meeting must be sent to members:
</p>
<ul>
	<li>on the association's website or in a social media group used by the association</li>
</ul>

<h3>10. Annual general meeting</h3>
<p>The following matters are dealt with at the annual general meeting of the association:</p>
<ol>
	<li>opening of the meeting</li>
	<li>
		election of the chairperson, the secretary, two scrutineers of the minutes and, if necessary,
		two vote counters for the meeting
	</li>
	<li>establishing that the meeting is lawful and has a quorum</li>
	<li>approval of the agenda of the meeting</li>
	<li>
		presentation of the financial statements, the annual report and the statement of the operations
		inspectors or auditors
	</li>
	<li>
		decision on adopting the financial statements and granting discharge from liability to the board
		and other accountable parties
	</li>
	<li>
		adoption of the action plan, the budget and the amounts of the joining fee and the membership
		fee
	</li>
	<li>election of the chairperson of the board and the other board members</li>
	<li>
		election of one or two operations inspectors and deputy operations inspectors, or one or two
		auditors and deputy auditors
	</li>
	<li>other matters mentioned in the notice of the meeting.</li>
</ol>
<p>
	If a member of the association wishes to have a matter dealt with at the annual general meeting,
	they must notify the board of it in writing in good time, so that the matter can be included in
	the notice of the meeting.
</p>

<h3>11. Amending the rules and dissolving the association</h3>
<p>
	A decision to amend these rules or to dissolve the association must be made at a meeting of the
	association by a majority of at least three quarters (3/4) of the votes cast. The notice of the
	meeting must mention the amendment of the rules or the dissolution of the association. If the
	association is dissolved, its assets are used to promote the purpose of the association in the
	manner determined by the meeting that decides on the dissolution. If the association is abolished,
	its assets are used for the same purpose.
</p>
