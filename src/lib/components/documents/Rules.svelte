<h3>1. Yhdistyksen nimi ja kotipaikka</h3>
<p>Yhdistyksen nimi on Mementomori ry ja sen kotipaikka on Jyväskylä.</p>

<h3>2. Tarkoitus ja toiminnan laatu</h3>
<p>
	Yhdistyksen tarkoituksena on edistää avointa, eurooppalaista, hajautettua, digitaalisesti
	suvereenia sosiaalista mediaa sekä avointa ja eettistä verkkoviestintää. Yhdistyksen tarkoituksena
	ei ole voiton tai muun taloudellisen ansion hankkiminen siihen osallisille, eikä sen toiminta
	kohdistu vain rajoitettuun henkilöpiiriin. Yhdistyksen ylläpitämien palvelimien käyttö on avointa
	ja maksutonta eikä edellytä jäsenyyttä.
</p>
<p>Tarkoituksensa toteuttamiseksi yhdistys:</p>
<ul>
	<li>voi järjestää kursseja, harjoitus- ja opetustilaisuuksia sekä muuta vastaavaa toimintaa</li>
	<li>voi järjestää kilpailuja, näytöksiä, retkiä, leirejä ja muita tapahtumia</li>
	<li>voi ylläpitää yhdistyksen sähköisiä viestintäkanavia</li>
	<li>voi julkaista yhdistyksen tiedotteita ja muuta viestintää eri viestintäkanavissa</li>
	<li>neuvoo ja ohjaa jäseniään</li>
	<li>osallistuu julkiseen keskusteluun alaan liittyvissä asioissa</li>
	<li>voi kerätä ja jakaa tietoa sekä harjoittaa tutkimustoimintaa</li>
	<li>kokoaa jäsenet yhteiseen toimintaan ja ylläpitää yhteyksiä muihin alan yhdistyksiin</li>
	<li>voi järjestää yhdistyksen tarkoitukseen liittyviä matkoja jäsenilleen</li>
	<li>voi hankkia tarvittavia aineistoja ja välineitä yhdistyksen käyttöön</li>
	<li>pyrkii järjestämään käyttöönsä tilat, joita yhdistyksen jäsenet voivat käyttää</li>
	<li>voi tehdä esityksiä ja aloitteita harrastusmahdollisuuksien lisäämiseksi</li>
	<li>
		voi tehdä esityksiä, aloitteita ja selvityksiä sekä antaa lausuntoja muille yhteisöille ja
		viranomaisille
	</li>
	<li>edistää avoimen lähdekoodin ja hajautetun median tunnettuutta ja eettisyyttä</li>
	<li>
		ylläpitää ja kehittää yleisölle avoimia ja maksuttomia yhteisöpalvelimia ja sähköisiä
		viestintäkanavia osana fediversumia (esimerkkinä palvelut mementomori.social ja
		chat.mementomori.social)
	</li>
</ul>
<p>Toimintansa tukemiseksi yhdistys voi, hankittuaan tarvittaessa asianomaisen luvan:</p>
<ul>
	<li>järjestää rahankeräyksiä ja arpajaisia</li>
	<li>ottaa vastaan avustuksia, lahjoituksia ja testamentteja</li>
	<li>myydä mainostilaa</li>
	<li>solmia sponsorisopimuksia</li>
</ul>

<h3>3. Jäsenet</h3>
<p>
	Yhdistykseen varsinaiseksi jäseneksi voidaan hyväksyä henkilö, joka hyväksyy yhdistyksen
	tarkoituksen. Kannattavaksi jäseneksi voidaan hyväksyä yksityinen henkilö tai oikeuskelpoinen
	yhteisö, joka haluaa tukea yhdistyksen tarkoitusta ja toimintaa. Varsinaiset jäsenet ja
	kannattavat jäsenet hyväksyy hakemuksesta yhdistyksen hallitus. Kunniapuheenjohtajaksi tai
	kunniajäseneksi voidaan hallituksen esityksestä yhdistyksen kokouksessa kutsua henkilö, joka on
	huomattavasti edistänyt ja tukenut yhdistyksen toimintaa.
</p>

<h3>4. Liittymis- ja jäsenmaksu</h3>
<p>
	Varsinaisilta jäseniltä ja kannattavilta jäseniltä perittävän liittymismaksun ja vuotuisen
	jäsenmaksun suuruudesta erikseen kummallekin jäsenryhmälle päättää vuosikokous.
	Kunniapuheenjohtaja ja kunniajäsenet eivät suorita jäsenmaksuja.
</p>

<h3>5. Hallitus</h3>
<p>
	Yhdistyksen asioita hoitaa hallitus, johon kuuluu vuosikokouksessa valitut puheenjohtaja ja 2-4
	muuta varsinaista jäsentä. Hallituksen toimikausi on valintakokousten välinen aika.
</p>
<p>
	Hallitus valitsee keskuudestaan varapuheenjohtajan sekä ottaa keskuudestaan tai ulkopuoleltaan
	sihteerin, rahastonhoitajan ja muut tarvittavat toimihenkilöt. Hallitus kokoontuu puheenjohtajan
	tai hänen estyneenä ollessaan varapuheenjohtajan kutsusta, kun he katsovat siihen olevan aihetta
	tai kun vähintään puolet hallituksen jäsenistä sitä vaatii. Hallitus on päätösvaltainen, kun
	vähintään puolet sen jäsenistä, puheenjohtaja tai varapuheenjohtaja mukaanluettuna on läsnä.
	Äänestykset ratkaistaan ehdottomalla ääntenenemmistöllä. Äänten mennessä tasan ratkaisee
	puheenjohtajan ääni, vaaleissa kuitenkin arpa.
</p>

<h3>6. Yhdistyksen nimen kirjoittaminen</h3>
<p>
	Yhdistyksen nimen kirjoittaa hallituksen puheenjohtaja yksin, varapuheenjohtaja, sihteeri,
	rahastonhoitaja tai hallituksen oikeuttama henkilö, kaksi yhdessä.
</p>

<h3>7. Tilikausi</h3>
<p>Yhdistyksen tilikausi on kalenterivuosi.</p>

<h3>8. Yhdistyksen kokoukset</h3>
<p>
	Yhdistyksen kokoukseen voidaan osallistua hallituksen tai yhdistyksen kokouksen niin päättäessä
	myös postitse taikka tietoliikenneyhteyden tai muun teknisen apuvälineen avulla kokouksen aikana
	tai ennen kokousta. Yhdistyksen kokous hyväksyy äänestys- ja vaalijärjestyksen.
</p>
<p>Yhdistyksen vuosikokous pidetään vuosittain hallituksen määräämänä päivänä tammi-toukokuussa.</p>
<p>
	Yhdistyksen kokouksissa on jokaisella varsinaisella jäsenellä, kunniapuheenjohtajalla ja
	kunniajäsenellä yksi ääni. Kannattavalla jäsenellä on kokouksessa läsnäolo- ja puheoikeus.
</p>
<p>
	Yhdistyksen kokouksen päätökseksi tulee, ellei säännöissä ole toisin määrätty, se mielipide, jota
	on kannattanut yli puolet annetuista äänistä. Äänten mennessä tasan ratkaisee kokouksen
	puheenjohtajan ääni, vaaleissa kuitenkin arpa.
</p>

<h3>9. Yhdistyksen kokousten koollekutsuminen</h3>
<p>
	Hallituksen on kutsuttava yhdistyksen kokoukset koolle vähintään 14 vuorokautta ennen kokousta.
	Kokouskutsu on lähetettävä jäsenille:
</p>
<ul>
	<li>yhdistyksen verkkosivulla tai yhdistyksen käyttämän sosiaalisen median ryhmässä</li>
</ul>

<h3>10. Vuosikokous</h3>
<p>Yhdistyksen vuosikokouksessa käsitellään seuraavat asiat:</p>
<ol>
	<li>kokouksen avaus</li>
	<li>
		valitaan kokouksen puheenjohtaja, sihteeri, kaksi pöytäkirjantarkastajaa ja tarvittaessa kaksi
		ääntenlaskijaa
	</li>
	<li>todetaan kokouksen laillisuus ja päätösvaltaisuus</li>
	<li>hyväksytään kokouksen työjärjestys</li>
	<li>esitetään tilinpäätös, vuosikertomus ja toiminnantarkastajien/tilintarkastajien lausunto</li>
	<li>
		päätetään tilinpäätöksen vahvistamisesta ja vastuuvapauden myöntämisestä hallitukselle ja muille
		vastuuvelvollisille
	</li>
	<li>
		vahvistetaan toimintasuunnitelma, tulo- ja menoarvio sekä liittymis- ja jäsenmaksujen suuruudet
	</li>
	<li>valitaan hallituksen puheenjohtaja ja muut jäsenet</li>
	<li>
		valitaan yksi tai kaksi toiminnantarkastajaa ja varatoiminnantarkastajaa taikka yksi tai kaksi
		tilintarkastajaa ja varatilintarkastajaa
	</li>
	<li>käsitellään muut kokouskutsussa mainitut asiat.</li>
</ol>
<p>
	Mikäli yhdistyksen jäsen haluaa saada jonkin asian yhdistyksen vuosikokouksen käsiteltäväksi, on
	hänen ilmoitettava siitä kirjallisesti hallitukselle niin hyvissä ajoin, että asia voidaan
	sisällyttää kokouskutsuun.
</p>

<h3>11. Sääntöjen muuttaminen ja yhdistyksen purkaminen</h3>
<p>
	Päätös sääntöjen muuttamisesta ja yhdistyksen purkamisesta on tehtävä yhdistyksen kokouksessa
	vähintään kolmen neljäsosan (3/4) enemmistöllä annetuista äänistä. Kokouskutsussa on mainittava
	sääntöjen muuttamisesta tai yhdistyksen purkamisesta. Yhdistyksen purkautuessa käytetään
	yhdistyksen varat yhdistyksen tarkoituksen edistämiseen purkamisesta päättävän kokouksen
	määräämällä tavalla. Yhdistyksen tullessa lakkautetuksi käytetään sen varat samaan tarkoitukseen.
</p>
